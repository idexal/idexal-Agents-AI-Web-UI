/**
 * Get page size CSS.
 */
function getPageSize(options: PDFExportOptions): string {
  const sizes: Record<string, string> = {
    a4: '@page { size: A4; }',
    letter: '@page { size: letter; }',
    legal: '@page { size: legal; }',
  }

  const margins = options.margins
  const marginCSS = `@page { 
    margin-top: ${margins.top}mm;
    margin-right: ${margins.right}mm;
    margin-bottom: ${margins.bottom}mm;
    margin-left: ${margins.left}mm;
  }`

  return `${sizes[options.pageSize] ?? sizes.a4} ${marginCSS}`
}

/**
 * Format message content with basic markdown.
 */
function formatMessageContent(content: string): string {
  let formatted = escapeHtml(content)

  // Code blocks
  formatted = formatted.replace(/```(\w+)?\n([\s\S]*?)```/g, '<pre><code>$2</code></pre>')

  // Inline code
  formatted = formatted.replace(/`([^`]+)`/g, '<code>$1</code>')

  // Bold
  formatted = formatted.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')

  // Italic
  formatted = formatted.replace(/\*([^*]+)\*/g, '<em>$1</em>')

  // Line breaks
  formatted = formatted.replace(/\n/g, '<br>')

  return formatted
}

/**
 * Get role label.
 */
function getRoleLabel(role: string, labels: Record<string, string>): string {
  switch (role) {
    case 'user':
      return labels.user ?? 'User'
    case 'assistant':
      return labels.assistant ?? 'Assistant'
    case 'system':
      return labels.system ?? 'System'
    default:
      return role
  }
}

/**
 * Format date.
 */
function formatDate(date: Date): string {
  return date.toLocaleDateString()
}

/**
 * Format date and time.
 */
function formatDateTime(date: Date): string {
  return date.toLocaleString()
}

/**
 * Escape HTML special characters.
 */
function escapeHtml(text: string): string {
  const div = document.createElement('div')
  div.textContent = text
  return div.innerHTML
}

/**
 * Download PDF export as HTML file.
 */
export function downloadPDFExport(result: PDFExportResult): void {
  const blob = new Blob([result.html], { type: 'text/html' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = result.filename.replace('.pdf', '.html')
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}

/**
 * Open PDF in new window for printing.
 */
export function printPDFExport(result: PDFExportResult): void {
  const printWindow = window.open('', '_blank')
  if (printWindow) {
    printWindow.document.write(result.html)
    printWindow.document.close()
    printWindow.print()
  }
}

/**
 * Copy PDF HTML to clipboard.
 */
export async function copyPDFExportToClipboard(result: PDFExportResult): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(result.html)
    return true
  } catch {
    return false
  }
}
