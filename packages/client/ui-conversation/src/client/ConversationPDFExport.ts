/**
 * Generate PDF export for conversation.
 */
export function exportConversationToPDF(
  conversation: PDFConversation,
  options: PDFExportOptions = DEFAULT_PDF_OPTIONS
): PDFExportResult {
  const labels = PDF_LABELS[options.language] ?? PDF_LABELS.en!
  const filename = options.filename ?? `conversation-${conversation.id}.pdf`

  const html = generatePDFHTML(conversation, options, labels)

  return {
    html,
    filename,
    mimeType: 'text/html',
  }
}

/**
 * Generate PDF HTML content.
 */
function generatePDFHTML(
  conversation: PDFConversation,
  options: PDFExportOptions,
  labels: Record<string, string>
): string {
  const styles = generateStyles(options)
  const pageSize = getPageSize(options)

  let html = `<!DOCTYPE html>
<html lang="${options.language}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(conversation.title)}</title>
  <style>
    ${styles}
    ${pageSize}
    ${options.customStyles ?? ''}
  </style>
</head>
<body>
  <div class="container">
    ${options.includeHeader ? generateHeader(conversation, labels) : ''}
    
    ${options.includeMetadata ? generateMetadata(conversation, labels) : ''}
    
    ${options.includeTableOfContents ? generateTOC(conversation, labels) : ''}
    
    <div class="messages-section">
      <h2>${labels.messages}</h2>
      <div class="messages-list">
        ${conversation.messages.map((msg, index) => generateMessage(msg, index, options, labels)).join('\n')}
      </div>
    </div>
    
    ${options.includeFooter ? generateFooter(labels) : ''}
  </div>
  
  ${options.includePageNumbers ? generatePageNumbersScript() : ''}
</body>
</html>`

  return html
}

/**
 * Generate header section.
 */
function generateHeader(
  conversation: PDFConversation,
  labels: Record<string, string>
): string {
  return `
    <header class="header">
      <div class="header-content">
        <h1 class="title">${escapeHtml(conversation.title)}</h1>
        <div class="subtitle">${labels.title}</div>
      </div>
    </header>
  `
}

/**
 * Generate metadata section.
 */
function generateMetadata(
  conversation: PDFConversation,
  labels: Record<string, string>
): string {
  const messageCount = conversation.messages.length
  const attachmentCount = conversation.messages.reduce(
    (sum, msg) => sum + (msg.attachments?.length ?? 0),
    0
  )

  return `
    <div class="metadata">
      <div class="metadata-grid">
        <div class="metadata-item">
          <span class="metadata-label">${labels.date}</span>
          <span class="metadata-value">${formatDate(conversation.createdAt)}</span>
        </div>
        <div class="metadata-item">
          <span class="metadata-label">${labels.messageCount}</span>
          <span class="metadata-value">${messageCount}</span>
        </div>
        ${conversation.participants && conversation.participants.length > 0 ? `
        <div class="metadata-item">
          <span class="metadata-label">${labels.participants}</span>
          <span class="metadata-value">${conversation.participants.join(', ')}</span>
        </div>
        ` : ''}
        ${attachmentCount > 0 ? `
        <div class="metadata-item">
          <span class="metadata-label">${labels.attachments}</span>
          <span class="metadata-value">${attachmentCount}</span>
        </div>
        ` : ''}
        ${conversation.tags && conversation.tags.length > 0 ? `
        <div class="metadata-item">
          <span class="metadata-label">${labels.tags}</span>
          <span class="metadata-value">${conversation.tags.join(', ')}</span>
        </div>
        ` : ''}
      </div>
    </div>
  `
}

/**
 * Generate table of contents.
 */
function generateTOC(
  conversation: PDFConversation,
  labels: Record<string, string>
): string {
  const userMessages = conversation.messages.filter(m => m.role === 'user')
  const assistantMessages = conversation.messages.filter(m => m.role === 'assistant')

  return `
    <div class="toc">
      <h2>${labels.tableOfContents}</h2>
      <ul>
        <li>${labels.user}: ${userMessages.length} ${labels.messages}</li>
        <li>${labels.assistant}: ${assistantMessages.length} ${labels.messages}</li>
      </ul>
    </div>
  `
}

/**
 * Generate a single message.
 */
function generateMessage(
  message: PDFMessage,
  index: number,
  options: PDFExportOptions,
  labels: Record<string, string>
): string {
  const roleLabel = getRoleLabel(message.role, labels)
  const roleClass = `message-${message.role}`

  return `
    <div class="message ${roleClass}" id="msg-${index}">
      <div class="message-header">
        <span class="message-role">${roleLabel}</span>
        ${options.includeTimestamps ? `
        <span class="message-time">${formatDateTime(message.timestamp)}</span>
        ` : ''}
      </div>
      <div class="message-content">
        ${formatMessageContent(message.content)}
      </div>
      ${options.includeAttachments && message.attachments && message.attachments.length > 0 ? `
      <div class="message-attachments">
        ${message.attachments.map(att => `
          <div class="attachment">
            <span class="attachment-icon">📎</span>
            <span class="attachment-name">${escapeHtml(att.name)}</span>
          </div>
        `).join('')}
      </div>
      ` : ''}
    </div>
  `
}

/**
 * Generate footer section.
 */
function generateFooter(labels: Record<string, string>): string {
  return `
    <footer class="footer">
      <div class="footer-content">
        <span>${labels.generatedBy}</span>
        <span>${labels.exportedAt} ${new Date().toLocaleString()}</span>
      </div>
    </footer>
  `
}

