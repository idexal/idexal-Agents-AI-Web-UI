/**
 * Conversation PDF Export for Idexal Agents.
 * Export conversations to PDF format with professional styling.
 */

/** Message interface */
export interface PDFMessage {
  id: string
  role: 'user' | 'assistant' | 'system'
  content: string
  timestamp: Date
  attachments?: Array<{
    type: string
    name: string
    url?: string
  }>
}

/** Conversation interface */
export interface PDFConversation {
  id: string
  title: string
  messages: PDFMessage[]
  createdAt: Date
  updatedAt: Date
  participants?: string[]
  tags?: string[]
}

/** PDF export options */
export interface PDFExportOptions {
  /** Include timestamps */
  includeTimestamps: boolean
  /** Include metadata */
  includeMetadata: boolean
  /** Include attachments list */
  includeAttachments: boolean
  /** Page size */
  pageSize: 'a4' | 'letter' | 'legal'
  /** Orientation */
  orientation: 'portrait' | 'landscape'
  /** Margins in mm */
  margins: {
    top: number
    right: number
    bottom: number
    left: number
  }
  /** Custom filename */
  filename: string | undefined
  /** Language for labels */
  language: 'en' | 'ar' | 'zh'
  /** Custom CSS styles */
  customStyles: string | undefined
  /** Include table of contents */
  includeTableOfContents: boolean
  /** Include page numbers */
  includePageNumbers: boolean
  /** Include header */
  includeHeader: boolean
  /** Include footer */
  includeFooter: boolean
}

/** PDF export result */
export interface PDFExportResult {
  /** HTML content ready for PDF generation */
  html: string
  /** Suggested filename */
  filename: string
  /** MIME type */
  mimeType: string
}

